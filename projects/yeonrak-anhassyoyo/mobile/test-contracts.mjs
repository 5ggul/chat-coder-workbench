import fs from 'node:fs';
import assert from 'node:assert/strict';
const app = fs.readFileSync(new URL('./App.tsx', import.meta.url), 'utf8');
const store = fs.readFileSync(new URL('./src/store.tsx', import.meta.url), 'utf8');
const api = fs.readFileSync(new URL('./src/api.ts', import.meta.url), 'utf8');
const config = JSON.parse(fs.readFileSync(new URL('./app.json', import.meta.url), 'utf8'));
assert.match(app, /90초 위기모드/);
assert.match(app, /봉인함/);
assert.match(app, /30일/);
assert.match(app, /90일/);
assert.match(app, /상대 관리/);
assert.match(store, /scheduleSealNotification/);
assert.match(store, /createRemoteSeal/);
assert.match(api, /Bearer/);
assert.match(api, /EXPO_PUBLIC_API_BASE_URL/);
assert.doesNotMatch(api, /body.*message|message.*body/i, 'message bodies must never be sent to the API');
assert.equal(config.expo.name, '연락안했어요');
assert.ok(config.expo.plugins.some(p => Array.isArray(p) && p[0] === 'expo-notifications'));
const emoji = /[\u{1F300}-\u{1FAFF}]/u;
assert.equal(emoji.test(app), false, 'emoji-based UI is prohibited');
console.log('mobile contracts ok');
